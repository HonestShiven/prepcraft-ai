// ===========================================================================================
// INTERVIEW.CONTEXT.JSX — React Context for Interview State Management.
//
// WHAT IS CONTEXT?
// React Context provides a way to pass data through the component tree without having
// to pass props down manually at every level ("prop drilling").
//
// WHAT THIS CONTEXT MANAGES:
//   1. loading   — Boolean flag indicating if an AI generation or fetch request is in progress.
//   2. report    — The currently active/viewed interview report object (for the report detail page).
//   3. reports   — Array of all interview reports belonging to the logged-in user (for the history list).
//
// WHO USES THIS CONTEXT?
//   - useInterview.js consumes this context via useContext(InterviewContext).
//   - Home.jsx and Interview.jsx consume useInterview() to access and mutate this state.
// ===========================================================================================

// Import createContext and useState from React.
// createContext creates the context object that components subscribe to.
// useState manages the local reactive state within the provider component.
import { createContext, useState } from "react";

// ── 1. Create the Context Object ──────────────────────────────────────────────
// InterviewContext is exported so custom hooks (like useInterview) can access it via useContext().
// Initially, default value is undefined (it gets populated by the Provider below).
export const InterviewContext = createContext();

// ── 2. Provider Component ─────────────────────────────────────────────────────
// InterviewProvider wraps components that need access to interview state.
// In App.jsx, it wraps the entire application inside the AuthProvider.
// "children" represents all nested components inside <InterviewProvider>...</InterviewProvider>.
export const InterviewProvider = ({ children }) => {

    // loading state: true when generating an AI report or fetching reports from the backend; false otherwise.
    // Used by UI components to show loading spinners or disable submit buttons.
    const [loading, setLoading] = useState(false);

    // report state: holds the single interview report object currently being viewed on the /interview/:id page.
    // Contains: { _id, title, matchScore, technicalQuestions, behavioralQuestions, skillGaps, preparationPlan, ... }
    const [report, setReport] = useState(null);

    // reports state: holds an array of all past reports generated by the authenticated user.
    // Populated by getReports() on the Home page to display the user's report history cards.
    const [reports, setReports] = useState([]);

    // The Provider component makes these state variables and their setter functions
    // available to any descendant component in the React tree.
    // Any component calling useContext(InterviewContext) gets this exact "value" object.
    return (
        <InterviewContext.Provider value={{ loading, setLoading, report, setReport, reports, setReports }}>
            {children}
        </InterviewContext.Provider>
    );
};