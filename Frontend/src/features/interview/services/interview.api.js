// ===========================================================================================
// INTERVIEW.API.JS — Axios HTTP Client & Interview API Service Functions.
//
// WHAT THIS FILE DOES:
//   1. Creates an Axios client instance configured for requests to the Express backend.
//   2. Implements four key interview service methods:
//      - generateInterviewReport: Sends multipart/form-data (resume file + text prompts)
//      - getInterviewReportById:  Fetches a single report document by MongoDB ObjectId
//      - getAllInterviewReports:  Fetches all report summaries created by the logged-in user
//      - generateResumePdf:       Calls the resume PDF endpoint with `responseType: "blob"`
// ===========================================================================================

// Import axios for making HTTP requests.
import axios from "axios";

// ── Shared Axios Instance ────────────────────────────────────────────────────
const api = axios.create({
    // baseURL points to Express backend running on local port 3000.
    baseURL: "http://localhost:3000",

    // withCredentials ensures the authentication JWT cookie is sent along with every interview request.
    // Without this, the authMiddleware on the backend would reject all calls with 401 Unauthorized.
    withCredentials: true,
});

/**
 * ── 1. Generate Interview Report ─────────────────────────────────────────────
 * Uploads user's self-description, job description, and PDF resume to the backend.
 * Uses FormData because it includes a binary file (PDF resume) alongside text fields.
 *
 * @param {Object} params
 * @param {string} params.jobDescription - Target job posting details.
 * @param {string} params.selfDescription - Candidate's personal intro / context.
 * @param {File}   params.resumeFile - The PDF resume file selected from the browser.
 * @returns {Promise<Object>} Returns JSON object containing { message, interviewReport }.
 */
export const generateInterviewReport = async ({ jobDescription, selfDescription, resumeFile }) => {

    // FormData is a browser API used to construct key/value pairs representing form fields.
    // It's the standard way to upload files (multipart/form-data) via HTTP.
    const formData = new FormData();

    // Append the text fields.
    formData.append("jobDescription", jobDescription);
    formData.append("selfDescription", selfDescription);

    // Append the actual File object; Multer on the backend looks for the field named "resume".
    formData.append("resume", resumeFile);

    // Send POST request with multipart/form-data content type header.
    const response = await api.post("/api/interview/", formData, {
        headers: {
            "Content-Type": "multipart/form-data"
        }
    });

    // Return the response body from the server.
    return response.data;
};

/**
 * ── 2. Get Single Interview Report By ID ─────────────────────────────────────
 * Retrieves the full report document for display on the /interview/:interviewId page.
 *
 * @param {string} interviewId - MongoDB ObjectId string of the interview report.
 * @returns {Promise<Object>} Returns { interviewReport: { ... } }.
 */
export const getInterviewReportById = async (interviewId) => {
    // GET request to /api/interview/report/:interviewId
    const response = await api.get(`/api/interview/report/${interviewId}`);

    return response.data;
};

/**
 * ── 3. Get All Interview Reports for Logged-In User ─────────────────────────
 * Fetches all past reports generated by the user to populate the history panel on Home.
 *
 * @returns {Promise<Object>} Returns { interviewReports: [ ... ] }.
 */
export const getAllInterviewReports = async () => {
    // GET request to /api/interview/
    const response = await api.get("/api/interview/");

    return response.data;
};

/**
 * ── 4. Generate & Download ATS-Optimized Resume PDF ──────────────────────────
 * Asks the backend to generate a tailored resume via Gemini AI and compile it
 * into a downloadable binary PDF via Puppeteer.
 *
 * NOTE: `responseType: "blob"` is crucial! By default, Axios parses responses as JSON or text.
 * When receiving binary files like PDFs, we must explicitly tell Axios to treat the response
 * as a raw binary Blob, otherwise the PDF will be corrupted into text characters.
 *
 * @param {Object} params
 * @param {string} params.interviewReportId - The ID of the report to base the resume on.
 * @returns {Promise<Blob>} Returns binary Blob data representing the PDF file.
 */
export const generateResumePdf = async ({ interviewReportId }) => {
    const response = await api.post(`/api/interview/resume/pdf/${interviewReportId}`, null, {
        responseType: "blob" // Receive binary response as Blob
    });

    return response.data;
};